type Tone = "light" | "dark";

/** Icon chips: black (or paper on dark) by default, brand colour on hover. */
export function SocialIcons({ tone = "light", size = 36, className = "" }: { tone?: Tone; size?: number; className?: string }) {
  return (
    <ul className={`flex items-center gap-1.5 ${className}`}>
      {site.socials.map((s) => {
        const icon = ICONS[s.label];
        if (!icon) return null;
        return (
          <li key={s.label}>
            <a
              href={s.href}
              target="_blank"
              rel="noreferrer"
              aria-label={s.label}
              title={s.label}
              className={`social-chip grid place-items-center rounded-[10px] transition-[background,color,box-shadow] duration-300 ${
                tone === "dark" ? "shadow-[0_0_0_1px_var(--line-dark)]" : "card"
              }`}
              style={{ width: size, height: size, ["--brand" as string]: icon.brand }}
              data-fill={icon.fill ? "1" : undefined}
              data-tone={tone}
            >
              <svg viewBox="0 0 24 24" width={size * 0.44} height={size * 0.44} aria-hidden fill="currentColor">
                <path d={icon.path} />
              </svg>
            </a>
          </li>
        );
      })}
    </ul>
  );
}
